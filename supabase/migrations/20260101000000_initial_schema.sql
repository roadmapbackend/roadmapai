CREATE EXTENSION IF NOT EXISTS "uuid-ossp";
CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- 1. Profiles & Learner Preferences
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT,
    learning_goal TEXT,
    skill_level TEXT DEFAULT 'intermediate' CHECK (skill_level IN ('beginner', 'intermediate', 'advanced', 'expert')),
    default_daily_hours NUMERIC(3,1) DEFAULT 2.0,
    subscription_tier TEXT DEFAULT 'free' CHECK (subscription_tier IN ('free', 'pro', 'enterprise')),
    stripe_customer_id TEXT,
    stripe_subscription_id TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Token & Cost Guardrails
CREATE TABLE IF NOT EXISTS public.token_budgets (
    user_id UUID PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
    tokens_used_current_cycle INTEGER DEFAULT 0,
    max_tokens_monthly INTEGER DEFAULT 250000,
    cycle_resets_at TIMESTAMPTZ DEFAULT (NOW() + INTERVAL '30 days'),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Roadmaps (Created by Agent 1: Roadmap Structure Agent)
CREATE TABLE IF NOT EXISTS public.roadmaps (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    title TEXT NOT NULL,
    domain_context TEXT NOT NULL,
    total_days INTEGER NOT NULL CHECK (total_days > 0),
    daily_hours_commitment NUMERIC(3,1) NOT NULL CHECK (daily_hours_commitment > 0),
    skill_level TEXT DEFAULT 'intermediate',
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'completed', 'archived')),
    metadata JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Roadmap Days (Day 1 ... Day N generated by Agent 1)
CREATE TABLE IF NOT EXISTS public.roadmap_days (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    roadmap_id UUID NOT NULL REFERENCES public.roadmaps(id) ON DELETE CASCADE,
    day_number INTEGER NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    learning_objectives JSONB DEFAULT '[]'::jsonb,
    status TEXT DEFAULT 'not_started' CHECK (status IN ('not_started', 'in_progress', 'completed')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (roadmap_id, day_number)
);

-- 5. Roadmap Topics (Topic 1 ... Topic N generated by Agent 2: Daily Structure Agent)
CREATE TABLE IF NOT EXISTS public.roadmap_topics (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    day_id UUID NOT NULL REFERENCES public.roadmap_days(id) ON DELETE CASCADE,
    roadmap_id UUID NOT NULL REFERENCES public.roadmaps(id) ON DELETE CASCADE,
    topic_number INTEGER NOT NULL,
    title TEXT NOT NULL,
    description TEXT,
    estimated_minutes INTEGER NOT NULL DEFAULT 45,
    status TEXT DEFAULT 'not_started' CHECK (status IN ('not_started', 'in_progress', 'completed')),
    created_at TIMESTAMPTZ DEFAULT NOW(),
    UNIQUE (day_id, topic_number)
);

-- 6. Topic Lessons & Resources (Generated by Agent 3: Daily Teacher Agent)
CREATE TABLE IF NOT EXISTS public.topic_lessons (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    topic_id UUID UNIQUE NOT NULL REFERENCES public.roadmap_topics(id) ON DELETE CASCADE,
    content_markdown TEXT NOT NULL,
    practical_examples JSONB DEFAULT '[]'::jsonb,
    citations JSONB DEFAULT '[]'::jsonb,
    recommended_courses JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. Agent Audit & Execution Logs
CREATE TABLE IF NOT EXISTS public.agent_execution_logs (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    agent_name TEXT NOT NULL,
    prompt_tokens INTEGER NOT NULL,
    completion_tokens INTEGER NOT NULL,
    total_cost_usd NUMERIC(8,6) DEFAULT 0.000000,
    latency_ms INTEGER NOT NULL,
    status TEXT DEFAULT 'success' CHECK (status IN ('success', 'failed', 'rate_limited')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- FUNCTIONS & TRIGGERS
-- 1. Increment token budget atomically
CREATE OR REPLACE FUNCTION public.increment_token_budget(p_user_id UUID, p_tokens INTEGER)
RETURNS VOID AS $$
BEGIN
    INSERT INTO public.token_budgets (user_id, tokens_used_current_cycle, max_tokens_monthly)
    VALUES (p_user_id, p_tokens, 250000)
    ON CONFLICT (user_id) DO UPDATE
    SET tokens_used_current_cycle = public.token_budgets.tokens_used_current_cycle + p_tokens,
        updated_at = NOW();
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 2. Automatic profile initialization
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
BEGIN
    INSERT INTO public.profiles (id, email, full_name)
    VALUES (
        NEW.id,
        NEW.email,
        NEW.raw_user_meta_data->>'full_name'
    )
    ON CONFLICT (id) DO NOTHING;

    INSERT INTO public.token_budgets (user_id, tokens_used_current_cycle, max_tokens_monthly)
    VALUES (NEW.id, 0, 250000)
    ON CONFLICT (user_id) DO NOTHING;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();

